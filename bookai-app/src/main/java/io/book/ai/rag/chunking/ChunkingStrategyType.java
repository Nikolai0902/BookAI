package io.book.ai.rag.chunking;

/** Тип стратегии разбиения документов на чанки. */
public enum ChunkingStrategyType {
    /** Разбиение по фиксированному количеству символов с перекрытием. */
    FIXED_SIZE,
    /** Разбиение по структуре документа: заголовки разделов, параграфы. */
    STRUCTURE
}
