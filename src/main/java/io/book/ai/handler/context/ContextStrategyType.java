package io.book.ai.handler.context;

/**
 * Перечисление доступных стратегий управления контекстом диалога.
 * <p>
 * Стратегия задаётся клиентом в {@link io.book.ai.api.AgentChatRequest} и фиксируется
 * на всё время сессии. Переключение стратегии в середине диалога не поддерживается.
 */
public enum ContextStrategyType {

    /** Полная история: все сообщения сессии передаются в LLM без изменений. */
    FULL_HISTORY,

    /**
     * LLM-суммаризация: сообщения старше последних N заменяются накопительным саммари,
     * которое инжектируется в системный промпт. Снижает расход токенов при длинных диалогах.
     */
    COMPRESSION,

    /**
     * Скользящее окно: в LLM передаются только последние N сообщений.
     * Старые сообщения хранятся в базе, но не отправляются.
     * Размер окна задаётся через {@code agent.context.sliding-window-size}.
     */
    SLIDING_WINDOW,

    /**
     * Ключевые факты: LLM получает краткий блок «key: value» фактов о диалоге
     * плюс последние N сообщений. Факты автоматически обновляются после каждого хода
     * отдельным LLM-вызовом (модель Haiku).
     */
    STICKY_FACTS,

    /**
     * Ветвление: диалог можно разветвить из любой точки, создав независимую ветку.
     * При ответе история собирается из корневой сессии до точки ветвления
     * плюс сообщения текущей ветки.
     */
    BRANCHING
}
