package io.book.ai.handler.context;

/**
 * Стратегия управления контекстом диалогового агента.
 * <p>
 * Каждая реализация отвечает за формирование набора сообщений и системного промпта,
 * которые будут переданы в LLM на текущем ходу. Опционально стратегия может выполнять
 * постобработку после получения ответа (например, обновление блока фактов).
 * <p>
 * Все реализации регистрируются как Spring-бины и автоматически собираются
 * в {@link ContextStrategyOrchestrator}.
 */
public interface ContextStrategy {

    /**
     * Возвращает тип стратегии, по которому оркестратор находит нужную реализацию.
     */
    ContextStrategyType type();

    /**
     * Формирует контекст для передачи в LLM.
     * <p>
     * Вызывается до обращения к LLM. На момент вызова сообщение пользователя
     * уже сохранено в базе, поэтому оно будет присутствовать в загружаемой истории.
     *
     * @param sessionId идентификатор сессии (или ветки при стратегии {@code BRANCHING})
     * @param model     идентификатор модели; может использоваться стратегией для генерации саммари
     * @return подготовленный контекст с сообщениями и опциональным системным промптом
     */
    ContextResult buildContext(String sessionId, String model);

    /**
     * Хук постобработки, вызываемый после сохранения ответа ассистента в базе.
     * <p>
     * По умолчанию ничего не делает и возвращает {@code null}. Переопределяется стратегиями,
     * которым нужно обновить состояние после каждого хода (например, {@code StickyFactsStrategy}
     * обновляет блок ключевых фактов).
     *
     * @param sessionId идентификатор сессии
     * @param model     идентификатор модели
     * @return обновлённое значение для включения в ответ клиенту, либо {@code null}
     */
    default String afterLlmResponse(String sessionId, String model) { return null; }
}
